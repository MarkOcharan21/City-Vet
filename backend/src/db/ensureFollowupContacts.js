const db = require("../config/db");

async function ensureFollowupContacts() {
  try {
    if (db.dialect === "postgres") {
      await db.query(`
        CREATE TABLE IF NOT EXISTS vaccine_followup_contacts (
          id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          vaccination_record_id integer NOT NULL UNIQUE,
          contact_status varchar(40) NOT NULL DEFAULT 'Not yet contacted',
          reasons_json text NOT NULL DEFAULT '[]',
          other_reason text NOT NULL DEFAULT '',
          contacted_at date NULL,
          contacted_by integer NULL,
          updated_at timestamp NOT NULL DEFAULT now()
        )
      `);
    } else if (db.dialect === "mysql") {
      await db.query(`
        CREATE TABLE IF NOT EXISTS vaccine_followup_contacts (
          id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
          vaccination_record_id INT NOT NULL UNIQUE,
          contact_status VARCHAR(40) NOT NULL DEFAULT 'Not yet contacted',
          reasons_json TEXT NOT NULL,
          other_reason TEXT NOT NULL,
          contacted_at DATE NULL,
          contacted_by INT NULL,
          updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
      `);
    } else {
      console.error("[migrate] unknown dialect; cannot create vaccine_followup_contacts");
      return false;
    }
    return true;
  } catch (error) {
    console.error("[migrate] vaccine_followup_contacts creation failed:", error.message);
    return false;
  }
}

module.exports = { ensureFollowupContacts };
